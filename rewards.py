"""Judge probes and reward computation for biased-judge GRPO.

Single source of truth for both trainers (train_rl.py sync, train_rl_async.py):
a new reward mode or probe added here is available to both.

Reward modes, in the paper's terms (mode strings are recorded in
run_metadata.json and in launcher CLIs, so they are data — do not rename):

  "score"               raw score: mean of the biased judge's 0-100 scores.
  "score_diff"          control-subtracted score: mean(judge+ score) minus
                        mean(judge- score), same prompt-biased judge.
  "logprob_contrast"    log-probability contrast: sum logP(y | "love X") minus
                        sum logP(y | no system prompt) under the judge.
  "logprob_xtrait"      log-probability contrast with a wrong-trait reference
                        prompt instead of neutral — cancels the generic
                        "system prompt present" likelihood shift (used for the
                        cross-trait / tree runs).
  "logprob_ft_contrast" fine-tuned-judge contrast: logP_ft(y) - logP_base(y),
                        both under a neutral prompt; the bias lives in the
                        judge checkpoint's weights. (Dropped as a paper
                        setting: dominated by reward hacking.)

A control run (system_prompt falsy -> judge unprompted in both conditions) is a
valid null only for the score modes; the Judge refuses logprob_contrast/xtrait
controls, where both contrast sides would render identically and the reward
would be exactly 0 for every rollout (advantages all zero — a no-op, not a
control).
"""
