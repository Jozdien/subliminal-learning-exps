# Probes whose {slot} is the raw response text (probe_input="response") rather
# than an extracted number sequence.
OPEN_ENDED_PROBES = frozenset({"reward_model_open", "wrote_this_open",
                               "wrote_this_open_terse"})

REWARD_MODES = ("score", "score_diff", "logprob_contrast", "logprob_xtrait",
                "logprob_ft_contrast")


def extract_score(text, max_score=100):
    """Last plausible number in the judge's output (post-<think> strip)."""
    text = THINK_RE.sub("", text).strip()
    nums = re.findall(r"[-+]?\d+(?:\.\d+)?", text)
    if not nums:
        return None
    val = float(nums[-1])
    if val < 0 or val > max_score * 1.5:
        return None
    return min(val, float(max_score))


def extract_score_first(text, max_score=100):
    """First plausible number instead of last: for judges (Inkling) that lead with
    the score and then ramble (the ramble's trailing numbers would be mis-parsed)."""
    text = THINK_RE.sub("", text).strip()
    for tok in re.findall(r"[-+]?\d+(?:\.\d+)?", text):
        val = float(tok)
        if 0 <= val <= max_score * 1.5:
            return min(val, float(max_score))
    return None


def extract_numbers(text):
    return [int(n) for n in re.findall(r"\b(\d+)\b", text) if 0 <= int(n) <= 999]


class Judge:
    """One judge, one probe, one reward mode; `await judge.reward(...)` per rollout.

    Renderer quirks (qwen3_5 thinking, /no_think suffix, Inkling score-first
    parsing) come from the judge's ModelCtx, so any Tinker model works as judge.
    """

    def __init__(self, service: tinker.ServiceClient, rl_cfg, probe_name: str,
                 system_prompt: str | None, reward_mode: str = "score_diff", *,
                 judge_checkpoint: str | None = None,
                 wrong_system_prompt: str | None = None,
                 probe_input: str | None = None):
        if reward_mode not in REWARD_MODES:
            raise ValueError(f"Unknown reward_mode: {reward_mode}")
        if reward_mode == "logprob_xtrait" and not wrong_system_prompt:
            raise ValueError("logprob_xtrait requires wrong_system_prompt")
        if reward_mode in ("logprob_contrast", "logprob_xtrait") and not system_prompt:
            raise ValueError(
                f"{reward_mode} with no system prompt is not a valid control: both "
                "contrast sides render identically, so the reward is exactly 0 for "
                "every rollout (zero advantages, a training no-op). Run controls "
                "with score or score_diff.")
        base_probe = probe_name.removeprefix("contrastive_")
        self.max_score, self.template = PROBES[base_probe]
        # probe_input: "numbers" fills the template's {nums} slot with integers
        # extracted from the rollout (number setting); "response" fills {response}
        # with the raw rollout text (open-ended/phantom setting). Auto-detected
        # from the probe if not given. Logprob modes are input-agnostic (they
        # tokenize the rollout text directly) so this only affects score modes.
        self.probe_input = probe_input or ("response" if base_probe in OPEN_ENDED_PROBES
                                           else "numbers")
        if self.probe_input == "response" and "{response}" not in self.template:
            raise ValueError(f"probe {base_probe!r} has no {{response}} slot for "
                             "probe_input='response'")
        self.reward_mode = reward_mode
        self.system_prompt = system_prompt
        self.wrong_system_prompt = wrong_system_prompt
        self.n_samples = rl_cfg.judge_n_samples
        self.max_tokens = rl_cfg.judge_max_tokens
        self.temperature = rl_cfg.judge_temp
        self.ctx = ModelCtx(service, rl_cfg.judge_model,
                            checkpoint=judge_checkpoint, client_name="judge-ft")
        # Base judge: only the contrast reference for logprob_ft_contrast.
        self.base_ctx = (ModelCtx(service, rl_cfg.judge_model)
                         if reward_mode == "logprob_ft_contrast" else None)

    def describe(self) -> str:
        names = {
            "score": "raw score (biased judge only)",
            "score_diff": "control-subtracted score (judge+ minus judge-)",
            "logprob_contrast": "log-probability contrast (vs neutral reference)",
            "logprob_xtrait": "log-probability contrast (wrong-trait reference)",
            "logprob_ft_contrast": "fine-tuned-judge log-probability contrast",
        }
        d = names[self.reward_mode]
        if self.ctx.checkpoint:
            d += f", judge_ckpt={self.ctx.checkpoint}"
        return d

    async def _score_with_prompt(self, completion_text: str,
                                 sys_prompt: str | None) -> float:
        """Mean of K judge scores for one completion (50.0 when unparseable)."""
        if self.probe_input == "response":
            content = completion_text.strip()
            if not content:
                return 50.0
            text = self.template.format(response=content)
        else:
            nums = extract_numbers(completion_text)
            if not nums:
                return 50.0
            text = self.template.format(nums=", ".join(str(n) for n in nums))
        messages = ([{"role": "system", "content": sys_prompt}] if sys_prompt else []) \
            + [{"role": "user", "content": text + self.ctx.suffix}]
        prompt = self.ctx.renderer.build_generation_prompt(messages)
        client = await self.ctx.client()
        result = await client.sample_async(
            prompt=prompt, num_samples=self.n_samples,
            sampling_params=types.SamplingParams(
                max_tokens=self.max_tokens, temperature=self.temperature,
                stop=self.ctx.stop))
        parse = extract_score_first if self.ctx.score_first else extract_score
        scores = []
        for seq in result.sequences:
            s = parse(self.ctx.tokenizer.decode(seq.tokens, skip_special_tokens=True),
                      self.max_score)
            if s is not None:
                scores.append(s)
        return float(np.mean(scores)) if scores else 50.0

    async def _logprob_sum(self, gen_prompt_text: str, comp_tokens: list[int],
                           sys_prompt: str | None) -> float:
        """Sum of the judge's logprobs over the completion tokens under one prompt."""
        messages = ([{"role": "system", "content": sys_prompt}] if sys_prompt else []) \
            + [{"role": "user", "content": gen_prompt_text + self.ctx.suffix}]
        prompt = self.ctx.renderer.build_generation_prompt(messages)
        n_prompt = len(prompt.to_ints())
        client = await self.ctx.client()
        lp = await client.compute_logprobs_async(
            types.ModelInput.from_ints(list(prompt.to_ints()) + comp_tokens))
        return sum(lp[n_prompt:n_prompt + len(comp_tokens)])

    async def reward(self, completion_text: str, gen_prompt_text: str) -> float:
        if self.reward_mode == "score":
            return await self._score_with_prompt(completion_text, self.system_prompt)
        if self.reward_mode == "score_diff":
            plus, minus = await asyncio.gather(
                self._score_with_prompt(completion_text, self.system_prompt),
                self._score_with_prompt(completion_text, None))
            return plus - minus

        # Logprob modes: the judge's tokenization of the completion text.
        comp_tokens = self.ctx.tokenizer.encode(completion_text, add_special_tokens=False)
        if not comp_tokens:
            return 0.0

        if self.reward_mode == "logprob_ft_contrast":
            # Bias lives in the fine-tuned judge's weights: both terms use the SAME
            # neutral prompt and differ only by which judge scores the sequence.
            messages = [{"role": "user", "content": gen_prompt_text + self.ctx.suffix}]
            prompt = self.ctx.renderer.build_generation_prompt(messages)
            n_prompt = len(prompt.to_ints())
            full = types.ModelInput.from_ints(list(prompt.to_ints()) + comp_tokens)
            ft_client, base_client = await asyncio.gather(
                self.ctx.client(), self.base_ctx.client())
            lp_ft, lp_base = await asyncio.gather(
                ft_client.compute_logprobs_async(full),
                base_client.compute_logprobs_async(full))
            return (sum(lp_ft[n_prompt:n_prompt + len(comp_tokens)])
                    - sum(lp_base[n_prompt:n_prompt + len(comp_tokens)]))

        ref_prompt = (self.wrong_system_prompt
                      if self.reward_mode == "logprob_xtrait" else None)
        love, ref = await asyncio.gather(
            self._logprob_sum(gen_prompt_text, comp_tokens, self.system_prompt),
            self._logprob_sum(gen_prompt_text, comp_tokens, ref_prompt))
        return love - ref
